def test_manifest_row_tampering_and_absent_capture_are_rejected(storage):
    _, _, _, _, _, _, snapshot, _, source_id = _setup(storage)
    preparer, _, prepared, company = _prepared(storage, snapshot, source_id)
    rows = json.loads(prepared.rows_bytes)
    rows[0]["market_cap"] = 777
    with pytest.raises(ValueError, match="typed query"):
        preparer.verify(replace(prepared, rows_bytes=canonical_bytes(rows)))
    rows[0]["enriched_payload"]["price"] = 777
    with pytest.raises(ValueError, match="retained hashes"):
        preparer.verify(replace(prepared, rows_bytes=canonical_bytes(rows)))
    company.captures["quote"] = {"status": "ABSENT", "reason": "unavailable"}
    with pytest.raises(ValueError, match="contradicts"):
        preparer.prepare([company], capture_mode="caller_captured_enrichment", limitations=["fixture"])


def test_new_source_before_activation_and_expired_lease_block_display(storage):
    engine, artifact, lease, repo, first, _, snapshot, candidate, source_id = _setup(storage)
    _, objects, prepared, _ = _prepared(storage, snapshot, source_id)
    _source(engine, artifact, lease, state="unavailable", revision=2, detected_at=NOW + timedelta(seconds=1))
