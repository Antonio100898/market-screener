def test_source_writer_waits_until_display_seals(storage, monkeypatch):
    engine, artifact, lease, repo, first, _, snapshot, candidate, source_id = _setup(storage)
    _, objects, prepared, _ = _prepared(storage, snapshot, source_id)
    writer_lease = _claim(engine, "display-source-writer")
    entered, release = Event(), Event()
    original = repo._activate
    def held(*args):
        entered.set()
        assert release.wait(10)
        return original(*args)
    monkeypatch.setattr(repo, "_activate", held)
    with ThreadPoolExecutor(max_workers=2) as pool:
        publisher = pool.submit(repo.publish_display, lease, request_key="display", candidate_ids=[candidate.candidate_id], expected_parent_release_id=first.release_id, prepared=prepared, object_store=objects)
        assert entered.wait(10)
        writer = pool.submit(_source, engine, artifact, writer_lease, state="unavailable", revision=2, detected_at=NOW + timedelta(seconds=1))
        try:
            blocked = False
            deadline = monotonic() + 5
            while monotonic() < deadline:
                with engine.connect() as connection:
                    blocked = connection.scalar(text("SELECT EXISTS (SELECT 1 FROM pg_stat_activity WHERE datname=current_database() AND wait_event_type='Lock' AND (query LIKE '%INSERT INTO source%' OR query LIKE '%FROM source_item%FOR UPDATE%'))"))
                if blocked:
                    break
                sleep(.01)
            assert blocked and not writer.done()
        finally:
            release.set()
        result = publisher.result(10)
        new_source_id = writer.result(10)
    assert result.projection_revision == 1
    assessed = SourceValidityRepository(engine).assess(result.release_id, [snapshot.security_id])["companies"][0]
    assert assessed["status"] == "REVALIDATION_REQUIRED"
    assert assessed["source_statuses"] == ["SOURCE_ACCESS_UNAVAILABLE"]
    assert assessed["dependencies"][0]["bound_observation_id"] == source_id
    assert assessed["dependencies"][0]["current_observation_id"] == new_source_id
