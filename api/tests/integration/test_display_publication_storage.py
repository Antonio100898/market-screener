def _input(storage, snapshot, source_id, *, price=10, ticker="ABT", cik="0000001800", assumed=False):
    engine, _ = storage
    settings = StorageSettings.from_env()
    objects = ImmutableObjectStore(create_s3_client(settings), settings.s3_bucket)
    artifacts = SqlArtifactRepository(engine)
    row = dict(ticker=ticker, cik=cik, name="Captured company", price=price, price_asof="2026-10-04",
               quote_currency="USD", shares=100, criteria=[{"n": 1, "status": "PASS", "value": 5}],
               n_pass=1, annual_eps={"2025": 2, "2024": 2, "2023": 2}, index_memberships=["S&P 500"])
    captures = {}
    for role in CAPTURE_FIELDS:
        fields = capture_fields(role, row)
        if any(value not in (None, [], {}) for value in fields.values()):
            raw = store_evidence(canonical_bytes(fields), "application/json", objects, artifacts)
            content = dict(role=role, row_fields=fields, provider="retained-test-provider", captured_at="2026-10-04T09:00:00Z", input_artifacts=[raw.content_sha256])
            artifact = store_evidence(canonical_bytes(content), "application/json", objects, artifacts)
            captures[role] = dict(status="CAPTURED", artifact_sha256=artifact.content_sha256)
        else:
            captures[role] = dict(status="ABSENT", reason="No input available in this fixture")
    assumed_row = {**row, "assumption_mode": {"status": "APPLIED", "requested": True, "applied": ["debt"]}} if assumed else None
    return DisplayReleasePreparer(engine, objects), objects, DisplayCompanyInput(snapshot.security_id, snapshot.snapshot_id, row, captures, (source_id,), assumed_row)


def _prepared(storage, snapshot, source_id, **kwargs):
    preparer, objects, company = _input(storage, snapshot, source_id, **kwargs)
    return preparer, objects, preparer.prepare([company], capture_mode="caller_captured_enrichment", limitations=["Synthetic stored output; no real financial regression certification"]), company


