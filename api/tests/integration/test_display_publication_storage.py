def test_whole_cohort_required_for_quote_only_child(storage):
    engine, artifact = storage
    lease = _claim(engine, "cohort")
    a = _company(engine, artifact)
    b = _company(engine, artifact, ticker="SECOND", identifier="2")
    a_source = _source(engine, artifact, lease)
    b_source = _source(engine, artifact, lease, identifier="2", key="filing-2")
    repo = PublicationRepository(engine, clock=lambda: NOW)
    first = repo.bootstrap(lease, request_key="initial")
    preparer, objects, a_input = _input(storage, a, a_source)
    _, _, b_input = _input(storage, b, b_source, ticker="SECOND", cik="0000000002")
    prepared = preparer.prepare([b_input, a_input], capture_mode="caller_captured_enrichment", limitations=["Fixture; not financial gate certification"])
    child = repo.publish_display(lease, request_key="whole-cohort", expected_parent_release_id=first.release_id, prepared=prepared, object_store=objects)
    assert child.member_count == 2
    with engine.connect() as connection:
        assert list(connection.scalars(select(p.c.ticker).where(p.c.release_id == child.release_id).order_by(p.c.universe_ordinal))) == ["SECOND", "ABT"]
    partial = preparer.prepare([a_input], capture_mode="caller_captured_enrichment", limitations=["Fixture"])
    with pytest.raises(ValueError, match="exactly one projection"):
        repo.publish_display(lease, request_key="partial", expected_parent_release_id=child.release_id, prepared=partial, object_store=objects)
    assert repo.active() == child
    with pytest.raises(ValueError, match="duplicate"):
        preparer.prepare([a_input, a_input], capture_mode="caller_captured_enrichment", limitations=["Fixture"])


def test_competing_display_children_keep_one_parent_owner(storage):
    engine, _, lease, repo, first, original, _, _, source_id = _setup(storage)
    _, objects, prepared, _ = _prepared(storage, original, source_id)
    second_lease = _claim(engine, "other-display-publisher")
    barrier = Barrier(2)
    def publish(token, key):
        barrier.wait(10)
        try:
            return repo.publish_display(token, request_key=key, expected_parent_release_id=first.release_id, prepared=prepared, object_store=objects)
        except StalePublicationParent as error:
            return error
    with ThreadPoolExecutor(max_workers=2) as pool:
        left = pool.submit(publish, lease, "left")
        right = pool.submit(publish, second_lease, "right")
        results = [left.result(10), right.result(10)]
    assert sum(isinstance(result, StalePublicationParent) for result in results) == 1
    winner = next(result for result in results if not isinstance(result, Exception))
    assert repo.active() == winner
    with engine.connect() as connection:
        assert connection.scalar(select(func.count()).select_from(p)) == 1


