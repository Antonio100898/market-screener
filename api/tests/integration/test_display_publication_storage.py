def test_full_display_child_and_commit_before_retry_pins_outputs(storage):
    engine, _, lease, repo, first, original, snapshot, candidate, source_id = _setup(storage)
    preparer, objects, prepared, company = _prepared(storage, snapshot, source_id, assumed=True)
    second = repo.publish_display(lease, request_key="display", expected_parent_release_id=first.release_id,
                                 candidate_ids=[candidate.candidate_id], prepared=prepared, object_store=objects)
    assert second.projection_revision == 1
    assert second.input_bundle_sha256 == prepared.input_bundle_sha256
    assert repo.release(first.release_id).projection_revision is None
    # Caller mutation after capture cannot affect pinned outputs.
    company.strict_row["price"] = 999
    with engine.connect() as connection:
        row = connection.execute(select(p).where(p.c.release_id == second.release_id)).mappings().one()
        assert row["price"] == row["enriched_payload"]["price"] == 10
        assert row["assumption_status"] == "APPLIED"
        assert row["assumed_payload"]["price"] == 10
    _, _, changed, _ = _prepared(storage, snapshot, source_id, price=12)
    third = repo.publish_display(lease, request_key="quote-only", expected_parent_release_id=second.release_id,
                                prepared=changed, object_store=objects)
    assert third.parent_release_id == second.release_id
    assert repo.publish_display(lease, request_key="display", expected_parent_release_id=first.release_id,
                               candidate_ids=[candidate.candidate_id], prepared=prepared, object_store=objects) == second
    with pytest.raises(PublicationIdentityConflict):
        repo.publish_display(lease, request_key="display", expected_parent_release_id=first.release_id,
                             candidate_ids=[candidate.candidate_id], prepared=changed, object_store=objects)
    with engine.connect() as connection:
        assert connection.scalar(select(p.c.price).where(p.c.release_id == second.release_id)) == 10
        assert connection.scalar(select(p.c.price).where(p.c.release_id == third.release_id)) == 12
        assert connection.scalar(select(release_company.c.snapshot_id).where(release_company.c.release_id == third.release_id)) == snapshot.snapshot_id


